"""c4_eval.py -- pre-registered home test (2026-10-02): does candidate psf_compile 2026-10-02.c4 (error-aware layout
through the device Target, changelog item 32) close the placement gap to Qiskit L3 found in Addenda 301 and 304?

Circuits: the five GAP families of Addendum 300, generated by the locked `benchmarks/gap_eval.py` (`family()`),
same seeds and sizes (2,079 circuits per device and arm).
Arms: C3 (release psf_compile 2026-10-02.1 with `target=<device Target>`, as the C3 arm of Addendum 304),
  C4 (candidate, the same call plus `error_aware_layout=True`),
  L3T (Qiskit transpile with the Target, optimization_level 3, approximation_degree 1.0 so that its noiseless
  output is exact).
Devices: FakeAuckland, FakeTorino, FakeKingston. Noise and metric as in GAP: infidelity 1 - <psi|rho|psi> of the
  final-layout qubits under NoiseModel.from_backend (density matrix). Also recorded per circuit: two-qubit gates
  placed on an edge whose reported error is >= 0.5 ("failed-edge uses"), gates on a qubit whose sx error is >= 0.5,
  and whether the candidate recompiled.

  python c3_eval.py run --repo <repo> --out <dir> --device <d> --arm <a> --family <F> [--smoke]
  python c3_eval.py score --out <dir>
"""
import argparse
import contextlib
import glob
import hashlib
import io
import json
import os
import subprocess
import sys
import time
import warnings

import numpy as np

warnings.simplefilter("ignore")
ARMS = ("C3", "C4", "L3T")
DEVICES = ("FakeAuckland", "FakeTorino", "FakeKingston")
FAMILIES = ("F1", "F2", "F3", "F4", "F5")
CAND = os.path.join("patches", "psf_compile_c4_2026-10-02", "psf_compile.py")
MAX_ACTIVE = 11


def norm_sha(path):
    with open(path, "rb") as f:
        txt = f.read().decode("utf-8").replace("\r\n", "\n")
    lines = [ln.rstrip() for ln in txt.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def run(args):
    from qiskit import transpile
    from qiskit.quantum_info import Statevector
    from qiskit_aer import AerSimulator
    from qiskit_aer.noise import NoiseModel
    from qiskit_ibm_runtime import fake_provider
    sys.path.insert(0, os.path.join(args.repo, "benchmarks"))
    sys.path.insert(0, args.repo)
    import core_fix_c2_eval as H
    import gap_eval as G
    lay = H.load_module(os.path.join(args.repo, "benchmarks", "psf_smart_layout.py"), "psl_c2")
    sys.modules["psf_smart_layout"] = lay
    mod = {"C3": H.load_module(os.path.join(args.repo, "psf_compile.py"), "psf_compile"),
           "C4": H.load_module(os.path.join(args.repo, CAND), "psf_compile_c4")}
    import psf_zero_core
    import qiskit
    backend = getattr(fake_provider, args.device)()
    tgt = backend.target
    cm = tgt.build_coupling_map()
    nat = [g for g in ("cx", "cz", "rz", "sx", "x") if g in tgt.operation_names]
    g2 = next(g for g in ("cz", "ecr", "cx") if g in tgt.operation_names)
    failed = {tuple(q) for q, p in tgt[g2].items() if p is not None and p.error is not None and p.error >= 0.5}
    failed_q = {q[0] for q, p in tgt["sx"].items() if p is not None and p.error is not None and p.error >= 0.5}
    opts = dict(method="density_matrix", max_parallel_threads=1, max_parallel_experiments=1)
    sims = {"noisy": AerSimulator(noise_model=NoiseModel.from_backend(backend), **opts), "ideal": AerSimulator(**opts)}
    meta = dict(c3=mod["C3"].VERSION, c4=mod["C4"].VERSION, layout=lay.LAYOUT_VERSION,
                core=getattr(psf_zero_core, "CORE_VERSION", None), qiskit=qiskit.__version__, python=sys.version.split()[0],
                git_head=subprocess.run(["git", "-C", args.repo, "rev-parse", "--short=7", "HEAD"], capture_output=True,
                                        text=True).stdout.strip(),
                sha=dict(script=norm_sha(os.path.abspath(__file__)), gap=norm_sha(G.__file__),
                         c4=norm_sha(os.path.join(args.repo, CAND))),
                device=args.device, arm=args.arm, family=args.family, smoke=args.smoke, failed_edges=len(failed),
                failed_qubits=len(failed_q),
                started=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    print("META", json.dumps(meta), flush=True)
    t0 = time.time()
    rows, circs, keep = [], [], []
    for params, qc in G.family(args.family, args.smoke):
        n = qc.num_qubits
        rc0 = mod["C4"].PRUNE_STATS["backstop"]
        t1 = time.perf_counter()
        with contextlib.redirect_stdout(io.StringIO()), warnings.catch_warnings():
            warnings.simplefilter("ignore")
            if args.arm == "L3T":
                out = transpile(qc, target=tgt, optimization_level=3, seed_transpiler=0, approximation_degree=1.0)
            else:
                kw = dict(target=tgt) if args.arm == "C3" else dict(target=tgt, error_aware_layout=True)
                out = mod[args.arm].compile_for_hardware(qc, coupling_map=cm, basis_gates=nat, entangling_basis="cx",
                                                         layout_search=True, seed_transpiler=0, **kw)
        tc = time.perf_counter() - t1
        fin = list(out.layout.final_index_layout(filter_ancillas=True)[:n])
        idx = [tuple(out.find_bit(q).index for q in ins.qubits) for ins in out.data]
        active = {i for t in idx for i in t}
        row = dict(params=params, n=n, compile_s=tc, two_q=sum(1 for t in idx if len(t) == 2), depth=out.depth(),
                   active=len(active), failed_uses=sum(1 for t in idx if len(t) == 2 and (t in failed or t[::-1] in failed)),
                   failed_q_uses=sum(1 for t in idx if any(i in failed_q for i in t)),
                   backstop=mod["C4"].PRUNE_STATS["backstop"] - rc0)
        rows.append(row)
        if len(active) > MAX_ACTIVE:
            row["too_wide"] = True
            continue
        c = out.copy()
        c.remove_final_measurements(inplace=True)
        c.save_density_matrix(qubits=fin)
        circs.append(c)
        keep.append((row, Statevector(qc).data))
    for which, key in (("noisy", "infid"), ("ideal", "infid_ideal")):
        if not circs:
            break
        res = sims[which].run(circs).result()
        for j, (row, psi) in enumerate(keep):
            rho = np.asarray(res.data(j)["density_matrix"])
            row[key] = float(1 - np.real(np.conj(psi) @ rho @ psi))
    name = f"c4_{args.device}_{args.arm}_{args.family}{'_smoke' if args.smoke else ''}.json"
    with open(os.path.join(args.out, name), "w") as f:
        json.dump(dict(meta=meta, rows=rows, wall_s=time.time() - t0), f)
    print(f"wrote {name}: {len(rows)} circuits, {len(circs)} simulated, {time.time() - t0:.0f} s", flush=True)


def verdict(ok, bad):
    return "REFUTED" if bad else ("CONFIRMED" if ok else "AMBIGUOUS")


def score(args):
    D, smoke = {}, None
    for p in sorted(glob.glob(os.path.join(args.out, "c4_*.json"))):
        r = json.load(open(p))
        m = r["meta"]
        smoke = m["smoke"]
        D[(m["device"], m["arm"], m["family"])] = r["rows"]
    rows = [x for v in D.values() for x in v]
    missing = [(d, a, f) for d in DEVICES for a in ARMS for f in FAMILIES if (d, a, f) not in D]
    wide = sum(1 for x in rows if x.get("too_wide"))
    p0i = max((x["infid_ideal"] for x in rows if "infid_ideal" in x), default=1.0)
    p0 = not missing and p0i <= 1e-6 and wide <= 0.05 * max(len(rows), 1)
    L = [f"# c4 score{' (SMOKE -- not a result)' if smoke else ''}", "",
         f"P0: {'PASS' if p0 else 'FAIL'} -- files {len(D)} of 45 (missing {missing}); noiseless infidelity max "
         f"{p0i:.1e} (<= 1e-6); too wide {wide} of {len(rows)}"]

    def pairs(d, fams, a, b):
        out = []
        for f, bc in fams:
            for x, y in zip(D.get((d, a, f), []), D.get((d, b, f), [])):
                if (bc is None or x["params"]["bc"] == bc) and "infid" in x and "infid" in y:
                    out.append((x, y))
        return out

    ratio = lambda pr: (np.mean([x["infid"] for x, _ in pr]) / max(np.mean([y["infid"] for _, y in pr]), 1e-12)
                        if pr else float("nan"))
    fams = [("F1", None), ("F2", None), ("F3", "o"), ("F3", "p"), ("F4", None), ("F5", None)]
    L += ["", "| family | device | C3/L3T | C4/L3T | C4/C3 | mean 2q C3 / C4 / L3T |", "|---|---|---|---|---|---|"]
    cells = {}
    for f, bc in fams:
        for d in DEVICES:
            r43 = ratio(pairs(d, [(f, bc)], "C4", "C3"))
            cells[(f + (bc or ""), d)] = r43
            tq = [np.mean([x["two_q"] for x in D.get((d, a, f), []) if bc is None or x["params"]["bc"] == bc]) for a in ARMS]
            L.append(f"| {f}{bc or ''} | {d} | {ratio(pairs(d, [(f, bc)], 'C3', 'L3T')):.3f} | "
                     f"{ratio(pairs(d, [(f, bc)], 'C4', 'L3T')):.3f} | {r43:.3f} | " + " / ".join(f"{v:.1f}" for v in tq) + " |")
    chain = {d: ratio(pairs(d, [("F3", "o"), ("F5", None)], "C4", "L3T")) for d in DEVICES}
    h1 = verdict(all(v <= 1.05 for v in chain.values()), any(v >= 1.20 for v in chain.values()))
    le = sum(v <= 1.0 for v in cells.values())
    h2 = verdict(le >= 16 and all(v <= 1.10 for v in cells.values()), le < 12 or any(v > 1.20 for v in cells.values()))
    c4l = {k: ratio(pairs(k[1], [(k[0][:2], (k[0][2:] or None))], "C4", "L3T")) for k in cells}
    h3 = verdict(all(v <= 1.10 for v in c4l.values()), any(v > 1.30 for v in c4l.values()))
    c4_failed = sum(x["failed_uses"] + x.get("failed_q_uses", 0) for (d, a, f), v in D.items() if a == "C4" for x in v)
    h4 = verdict(c4_failed == 0, c4_failed > 0)
    med = {a: float(np.median([x["compile_s"] for (d, aa, f), v in D.items() if aa == a for x in v])) for a in ARMS}
    h5 = verdict(med["C4"] <= 2 * med["C3"], med["C4"] > 3 * med["C3"])
    nb = sum(x.get("backstop", 0) > 0 for (d, a, f), v in D.items() if a == "C4" for x in v)
    fmt = lambda dct: ", ".join(f"{k} {v:.3f}" for k, v in dct.items())
    L += ["", f"C4 backstop recompiles (item 31 path): {nb}", "", "## Predictions", "",
          f"- H1 (chains: C4/L3T <= 1.05 on every device): **{h1}** ({fmt(chain)})",
          f"- H2 (C4 <= C3 in >= 16 of 18 cells and no cell > 1.10): **{h2}** ({le} of 18 <= 1.0; max {max(cells.values()):.3f})",
          f"- H3 (C4/L3T <= 1.10 in every cell): **{h3}** (max {max(c4l.values()):.3f})",
          f"- H4 (C4 never uses a failed coupler or qubit): **{h4}** ({c4_failed} uses)",
          f"- H5 (median compile time C4 <= 2 x C3): **{h5}** (C3 {med['C3']:.3f} s, C4 {med['C4']:.3f} s)"]
    L.append("\nReported: median compile s " + ", ".join(f"{a} {v:.3f}" for a, v in med.items()))
    txt = "\n".join(L) + "\n"
    with open(os.path.join(args.out, "score.md"), "w") as f:
        f.write(txt)
    print(txt)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("part", choices=("run", "score"))
    ap.add_argument("--repo")
    ap.add_argument("--out", required=True)
    ap.add_argument("--device", choices=DEVICES)
    ap.add_argument("--arm", choices=ARMS)
    ap.add_argument("--family", choices=FAMILIES)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    (run if args.part == "run" else score)(args)


if __name__ == "__main__":
    main()
